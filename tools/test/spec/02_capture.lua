-- Capture: a clicked profession link's window, or your own, read and stored only for a guild member.
return function(test, H)
    -- Ola (the client, Tailoring), Kari and Siri in the guild, Per outside it.
    local function World(quirks, opts)
        local w = H.World()
        for k, v in pairs(quirks or {}) do w.quirks[k] = v end
        w:AddPlayer("Kari Berg", { profs = { [171] = { 2330, 2331, 3447 } } })
        w:AddPlayer("Siri Dahl", { profs = { [171] = { 2330, 17556 }, [333] = { 7418, 25124 } }, rank = 280, max = 300 })
        w:AddPlayer("Per Fremmed", { guild = false, profs = { [164] = { 2662, 2663 } } })
        local ola = w:AddClient("Ola Nord", opts or { profs = { [197] = { 2387, 2393, 3914 } } })
        w:Settle()
        return w, ola
    end

    test("a guild member's link: their learned recipes stored, the player told", function()
        local w, ola = World()
        ola:Mark()
        ola:ClickLink("Kari Berg", 171)
        H.eq(H.lines(ola:Said()), "Stored 3 Alchemy recipes from Kari Berg.")
        local p = ola:Bucket().members["Kari Berg"].profs[171]
        H.eq(p.n, 3)
        H.eq(p.name, "Alchemy")
        H.eq(p.from, "link")
        H.eq(p.rank, 150, "the level from the base line (the child's is 0/0)")
        H.eq(p.max, 225)
        H.ok(p.recipes[2330] and p.recipes[2331] and p.recipes[3447])
        H.no(p.recipes[7181], "a recipe they haven't learned")
        H.eq(ola:Bucket().members["Kari Berg"].guid, w.players["Kari Berg"].guid)
        H.eq(ola.ns.DB:Recipes()[3447].n, "Healing Potion")
        H.eq(ola:Holders("Healing Potion"), "Kari Berg")
        H.eq(ola:Logged("Capture", "whose: Kari Berg by guid"), 1)
    end)

    test("the same link again is up to date; a recipe learned since changes it", function()
        local w, ola = World()
        ola:ClickLink("Kari Berg", 171)
        ola:CloseProfession()
        local rev = ola:Bucket().rev
        ola:Mark()
        ola:ClickLink("Kari Berg", 171)
        H.eq(H.lines(ola:Said()), "Kari Berg's Alchemy is up to date (3 recipes).")
        H.eq(ola:Bucket().rev, rev)
        ola:CloseProfession()
        w.players["Kari Berg"]:Learn(171, { 7181 })
        w.players["Kari Berg"]:Unlearn(171, 2331)
        ola:Mark()
        ola:ClickLink("Kari Berg", 171)
        H.eq(H.lines(ola:Said()), "Stored 3 Alchemy recipes from Kari Berg.")
        H.eq(ola:Bucket().rev, rev + 1)
        H.eq(ola:Holders("Greater Healing Potion"), "Kari Berg")
        H.eq(ola:Holders("Minor Mana Potion"), nil, "stored whole: what they no longer show is gone")
    end)

    -- Whose professions are stored, "who:line" (a guild bucket holds our own skill sheet from login on).
    local function Stored(c)
        local out = {}
        for who, m in pairs(c:Bucket() and c:Bucket().members or {}) do
            for line in pairs(m.profs) do out[#out + 1] = who .. ":" .. line end
        end
        table.sort(out)
        return table.concat(out, " ")
    end

    test("someone outside the guild: nothing stored", function()
        local w, ola = World()
        ola:Mark()
        ola:ClickLink("Per Fremmed", 164)
        H.eq(H.lines(ola:Said()), "Per Fremmed isn't in your guild: their recipes weren't stored.")
        H.eq(Stored(ola), "", "nothing of theirs (our own skill sheet only)")
    end)

    test("your own profession: stored once, quietly after", function()
        local w, ola = World()
        ola:Mark()
        ola:OpenProfession(197)
        H.eq(H.lines(ola:Said()), "Stored your 3 Tailoring recipes.")
        ola:CloseProfession()
        ola:Mark()
        ola:OpenProfession(197)
        H.eq(#ola:Said(), 0)
        H.eq(ola:Bucket().members["Ola Nord"].profs[197].from, "own")
        H.eq(ola:Holders("Linen Cloak"), "Ola Nord")
    end)

    test("an NPC's crafting window and the guild crafters view are skipped", function()
        local w, ola = World()
        ola:OpenNPC(171)
        H.eq(ola:Logged("Capture", "an NPC's crafting: skipped"), 1)
        ola:CloseProfession()
        ola:OpenWindow({ owner = w.players["Kari Berg"], line = 171, kind = "guild" })
        H.eq(ola:Logged("Capture", "guild crafters view: skipped"), 1)
        H.eq(Stored(ola), "")
    end)

    test("events: only TRADE_SKILL_SHOW while the window is shut", function()
        local w, ola = World()
        H.ok(ola:Listening("TRADE_SKILL_SHOW"))
        H.no(ola:Listening("TRADE_SKILL_LIST_UPDATE"))
        ola:OpenProfession(197)
        H.ok(ola:Listening("TRADE_SKILL_LIST_UPDATE"))
        H.ok(ola:Listening("TRADE_SKILL_DATA_SOURCE_CHANGED"))
        ola:CloseProfession()
        H.no(ola:Listening("TRADE_SKILL_LIST_UPDATE"))
        H.no(ola:Listening("TRADE_SKILL_CLOSE"))
        H.no(ola:Listening("GUILD_ROSTER_UPDATE"), "the roster's only while asked")
    end)

    test("the list's burst is read once, after it's quiet", function()
        local w, ola = World()
        ola:ClickLink("Kari Berg", 171)
        H.eq(ola:Logged("Capture", "read Alchemy"), 1)
        H.eq(ola:Logged("Capture", "data source changing"), 0)
    end)

    test("a shift-click puts the link in the chat line and opens nothing", function()
        local w, ola = World()
        ola:ClickLink("Kari Berg", 171, { button = "shift" })
        H.eq(ola:Logged("Capture", "link clicked"), 1)
        H.eq(Stored(ola), "")
    end)

    test("another link with the window open: the new source is read and announced too", function()
        local w, ola = World()
        ola:ClickLink("Kari Berg", 171)
        ola:Mark()
        ola:ClickLink("Siri Dahl", 333)
        H.eq(H.lines(ola:Said()), "Stored 2 Enchanting recipes from Siri Dahl.")
        ola:ClickLink("Kari Berg", 171)
        H.eq(ola:CountPrinted("Kari Berg's Alchemy is up to date"), 1)
        H.eq(ola:Holders("Minor Wizard Oil"), "Siri Dahl")
        ola:ClickLink("Siri Dahl", 171)
        H.eq(ola:Holders("Minor Healing Potion"), "Kari Berg, Siri Dahl", "holders sorted")
    end)

    test("a link that opens the window at once (before the click's hook) is still whose it is", function()
        local w, ola = World({ linkSync = true })
        ola:ClickLink("Kari Berg", 171)
        H.eq(ola:Holders("Healing Potion"), "Kari Berg")
    end)

    test("no name from IsTradeSkillLinked: the link's GUID says whose", function()
        local w, ola = World({ linkedName = false })
        ola:ClickLink("Siri Dahl", 171)
        H.eq(ola:Holders("Major Healing Potion"), "Siri Dahl")
    end)

    test("no GUIDs in the roster: the window's name says whose", function()
        local w, ola = World({ rosterGuid = false })
        ola:ClickLink("Siri Dahl", 171)
        H.eq(ola:Logged("Capture", "whose: Siri Dahl by name"), 1)
        H.eq(ola:Holders("Major Healing Potion"), "Siri Dahl")
    end)

    test("neither: GetPlayerInfoByGUID's name, a first name alone too when only one member has it", function()
        local w, ola = World({ rosterGuid = false, linkedName = false })
        ola:ClickLink("Siri Dahl", 171)
        H.eq(ola:Holders("Major Healing Potion"), "Siri Dahl")
        w.quirks.guidName = "first"
        ola:ClickLink("Kari Berg", 171)
        H.eq(ola:Logged("Capture", "whose: Kari Berg by first"), 1)
        H.eq(ola:Holders("Healing Potion"), "Kari Berg")
    end)

    test("a first name two members share, and no other clue: nothing stored", function()
        local w, ola = World({ rosterGuid = false, linkedName = false, guidName = "first" })
        w:AddPlayer("Kari Hansen", { profs = { [164] = { 3115 } } })
        ola.ns.Guild:Refresh(true)
        w:Run(1)
        ola:Mark()
        ola:ClickLink("Kari Hansen", 164)
        H.eq(H.lines(ola:Said()), "Couldn't tell whose profession this is: nothing stored.")
        H.eq(ola:Holders("Rough Sharpening Stone"), nil)
    end)

    test("nobody at all: told so", function()
        local w, ola = World({ rosterGuid = false, linkedName = false, guidName = false })
        ola:Mark()
        ola:ClickLink("Kari Berg", 171)
        H.eq(H.lines(ola:Said()), "Couldn't tell whose profession this is: nothing stored.")
    end)

    test("a client without IsTradeSkillLinked: a fresh link click makes it linked", function()
        local w, ola = World({ noIsLinked = true })
        ola:ClickLink("Kari Berg", 171)
        H.eq(ola:Holders("Healing Potion"), "Kari Berg")
        ola:CloseProfession()
        ola:OpenProfession(197)
        H.eq(ola:Holders("Linen Cloak"), "Ola Nord", "no link: your own")
    end)

    test("a stale link click doesn't name a window opened much later", function()
        local w, ola = World({ noIsLinked = true })
        ola:ClickLink("Kari Berg", 171, { button = "shift" })
        w:Run(ola.ns.Config.LINK_FRESH + 1)
        ola:OpenProfession(197)
        H.eq(ola:Holders("Linen Cloak"), "Ola Nord")
        H.eq(ola:Bucket().members["Kari Berg"], nil)
    end)

    test("membership not known yet: held until the roster comes", function()
        local w, ola = World({ rosterPartial = 1 })
        H.no(ola.ns.Guild.complete)
        ola:Mark()
        ola:ClickLink("Siri Dahl", 171)
        H.eq(H.lines(ola:Said()), "Waiting for the guild roster before storing Siri Dahl's Alchemy.")
        H.eq(#ola.ns.Capture.held, 1)
        H.eq(ola.rosterAsked, 2, "asked at once (and at settle)")
        w:Run(5)
        H.eq(ola.rosterAsked, 2, "an incomplete answer isn't asked again at once")
        w.quirks.rosterPartial = nil
        w:Run(ola.ns.Config.ROSTER_INTERVAL)
        H.eq(ola.rosterAsked, 3)
        H.eq(#ola.ns.Capture.held, 0)
        H.eq(ola:Holders("Major Healing Potion"), "Siri Dahl")
    end)

    test("held: a non-member is dropped once the roster says so; a stale roster keeps it held", function()
        local w, ola = World({ rosterPartial = 1, rosterGuid = false })
        w.quirks.rosterIgnored = true -- (the server ignores the request: the timeout reads the cache, stale)
        ola:ClickLink("Per Fremmed", 164)
        H.eq(#ola.ns.Capture.held, 1)
        w:Run(ola.ns.Config.ROSTER_TIMEOUT + 1)
        H.eq(ola:Logged("Guild", "(stale)"), 1)
        H.eq(#ola.ns.Capture.held, 1)
        w.quirks.rosterIgnored, w.quirks.rosterPartial = nil, nil
        w:Run(ola.ns.Config.ROSTER_INTERVAL)
        H.eq(#ola.ns.Capture.held, 0)
        H.eq(ola:CountPrinted("Per Fremmed isn't in your guild"), 1)
    end)

    test("held: only the newest per who and profession, and no more than HELD_MAX", function()
        local w, ola = World({ rosterPartial = 1, rosterIgnored = true })
        ola.ns.Config.HELD_MAX = 2
        ola:ClickLink("Siri Dahl", 171)
        ola:ClickLink("Siri Dahl", 171)
        H.eq(#ola.ns.Capture.held, 1)
        ola:ClickLink("Siri Dahl", 333)
        ola:ClickLink("Kari Berg", 171)
        H.eq(#ola.ns.Capture.held, 2)
        H.eq(ola.ns.Capture.held[1].line, 333, "the oldest went")
    end)

    test("outside a guild: nothing stored", function()
        local w, ola = World(nil, { guild = false, profs = { [197] = { 2387 } } })
        ola:Mark()
        ola:ClickLink("Kari Berg", 171)
        H.eq(H.lines(ola:Said()), "You're not in a guild: nothing stored.")
        ola:CloseProfession()
        ola:OpenProfession(197)
        H.eq(ola:CountPrinted("Stored"), 0)
        H.eq(next(ola.ns.DB.data.guilds), nil)
    end)

    test("nothing learned, or no profession read: nothing stored", function()
        local w, ola = World()
        w:AddPlayer("Tom Tom", { profs = { [164] = {} } })
        ola.ns.Guild:Refresh(true)
        w:Run(1)
        ola:ClickLink("Tom Tom", 164)
        H.eq(ola:Logged("Capture", "not stored: empty"), 1)
        ola:CloseProfession()
        ola.env.C_TradeSkillUI.GetBaseProfessionInfo = function() return nil end
        ola.env.C_TradeSkillUI.GetChildProfessionInfo = function() return nil end
        ola:OpenProfession(197)
        H.eq(ola:Logged("Capture", "no profession read"), 1)
    end)

    test("secret recipe names: stored by id, shown as #id", function()
        local w, ola = World()
        local open = ola.OpenWindow
        ola.OpenWindow = function(c, win, run) win.secretNames = true; return open(c, win, run) end
        ola:ClickLink("Kari Berg", 171)
        local rows = ola.ns.Index:Search("Proffene", "3447")
        H.eq(rows[1].name, "#3447")
        H.eq(H.lines(rows[1].holders), "Kari Berg")
    end)

    test("links: retail's form, a GUID anywhere, and what isn't one", function()
        local w, ola = World()
        local P = ola.ns.Capture.ParseLink
        local r = P("trade:Player-6841-001BD719:2259:171")
        H.eq(r.guid, "Player-6841-001BD719")
        H.eq(r.spell, 2259)
        H.eq(r.line, 171)
        r = P("|cffffd000|Htrade:7:Player-1-0A:171|h[Alchemy]|h|r")
        H.eq(r.guid, "Player-1-0A")
        H.eq(r.spell, 171)
        r = P("trade:2259:150:225")
        H.eq(r.guid, nil)
        H.eq(r.spell, 2259)
        H.eq(P("item:1234"), nil)
        H.eq(P(nil), nil)
    end)
end
