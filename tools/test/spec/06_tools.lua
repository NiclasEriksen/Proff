-- The desktop tools on a SavedVariables file as the client writes it: tools/db.lua and tools/log.lua.
return function(test, H)
    local function Run(cmd)
        local p = io.popen(cmd .. " 2>&1")
        local out = p:read("*a")
        p:close()
        return out
    end
    local function Saved()
        local w = H.World()
        w:AddPlayer("Kari Berg", { profs = { [171] = { 2330, 3447 } } })
        local ola = w:AddClient("Ola Nord", { profs = { [197] = { 2387 } } })
        w:Settle()
        ola:OpenProfession(197)
        ola:ClickLink("Kari Berg", 171)
        ola:Slash("probe roster")
        ola:Logout()
        local path = os.tmpname()
        ola:WriteSaved(path)
        return path
    end

    test("tools/db.lua: summary, search, who, check", function()
        local path = Saved()
        local out = Run("luajit tools/db.lua -f " .. path)
        H.match(out, "Proffene: 2 members, 2 professions, 3 recipes")
        H.match(out, "Alchemy +1 members +2 recipes")
        out = Run("luajit tools/db.lua -f " .. path .. " search healing")
        H.match(out, "Proffene: 2 match \"healing\"")
        H.match(out, "Healing Potion +Alchemy +Kari Berg")
        out = Run("luajit tools/db.lua -f " .. path .. " -g Proffene who Ola Nord")
        H.match(out, "Proffene: Tailoring 150/225, 1 recipes, from own")
        out = Run("luajit tools/db.lua -f " .. path .. " check")
        H.match(out, "schema in file 3, ours 3")
        H.match(Run("luajit tools/db.lua -f " .. path .. " nope"), "unknown command")
        H.match(Run("luajit tools/db.lua -h"), "who knows a recipe")
        os.remove(path)
    end)

    test("tools/log.lua: the session, a module, a probe's dump", function()
        local path = Saved()
        local out = Run("luajit tools/log.lua -f " .. path)
        H.match(out, "Session +start dev, Ola Nord")
        H.match(out, "Recipes +new Kari Berg Alchemy")
        out = Run("luajit tools/log.lua -f " .. path .. " -m Capture")
        H.no(out:find("Recipes", 1, true))
        H.match(out, "whose: Kari Berg by guid")
        out = Run("luajit tools/log.lua -f " .. path .. " --dump probe.roster")
        H.match(out, "Player%-6841")
        out = Run("luajit tools/log.lua -f " .. path .. " --db guilds")
        H.match(out, "Kari Berg")
        os.remove(path)
    end)
end
