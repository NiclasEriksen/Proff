-- luacheck's config, built from the test harness's stub client (Dyreparken's tools/lint_config.lua). One list of
-- the client API, the stubs': an API the addon starts using must be stubbed (tools/test/harness/env/*.lua)
-- before lint accepts it, as the tests already demand.
--
--   luajit tools/lint_config.lua > <file>; luacheck --config <file> .     (tools/check.sh does both)
--
-- The C_* namespaces are listed with their fields, so C_TradeSkillUI.GetRecipeinfo (a wrong case) is caught.
package.path = "tools/test/?.lua;" .. package.path
local H = require("harness")

local w = H.World()
w:AddPlayer("Lint Peer", { profs = { [171] = { 2330 } } })
local c = w:AddClient("Lint Klient")
w:Settle()
c:ClickLink("Lint Peer", 171) -- (Blizzard's frames made then: ProfessionsFrame)
local env = c:BuildEnv()
for k, v in pairs(c.env) do
    if rawget(env, k) == nil and type(k) == "string" and not k:match("^Proff") and not k:match("^SLASH_") then
        env[k] = v
    end
end

-- Read, but only behind a check that they exist: not stubbed on purpose, so the tests run without them.
local OPTIONAL = {
    "GetAddOnMetadata",      -- Init: C_AddOns.GetAddOnMetadata first
    "BugGrabber",            -- Dev/Errors: the other addon, when loaded
    "EventRegistry",         -- Dev/Errors: BugGrabber's callback
}
-- Fields a probe asks for, existing or not (Dev/Probe.lua: what this client has).
local OPTIONAL_FIELDS = { C_TradeSkillUI = { "GetTradeSkillLine", "GetTradeSkillDisplayName", "GetTradeSkillListLink" } }
local OURS = { ProffDB = true, ProffDebugDB = true, SlashCmdList = true }
for _, k in ipairs(OPTIONAL) do if env[k] == nil then env[k] = true end end

local plain, spaced = {}, {}
for k, v in pairs(env) do
    if type(k) == "string" and k:match("^[%a_][%w_]*$") and k ~= "_G" and not OURS[k] then
        if type(v) == "table" and k:match("^C_") then
            local fields = {}
            for f in pairs(v) do if type(f) == "string" then fields[#fields + 1] = f end end
            for _, f in ipairs(OPTIONAL_FIELDS[k] or {}) do if v[f] == nil then fields[#fields + 1] = f end end
            table.sort(fields)
            spaced[#spaced + 1] = { k, fields }
        else
            plain[#plain + 1] = k
        end
    end
end
table.sort(plain)
table.sort(spaced, function(a, b) return a[1] < b[1] end)

local out = {}
local function P(s) out[#out + 1] = s end
P("-- GENERATED by tools/lint_config.lua from the harness's stubs; don't edit.")
P('std = "lua51"')
P("max_line_length = false")
-- tools/ run on the desktop (luajit, with io and os); Dev/ in game like the rest.
P('exclude_files = { "Libs/**", "tools/**", ".claude/**" }')
P('globals = { "ProffDB", "ProffDebugDB", "SlashCmdList", "SLASH_PROFF1" }')
P("read_globals = {")
for _, k in ipairs(plain) do P(("    %q,"):format(k)) end
for _, e in ipairs(spaced) do
    local f = {}
    for _, x in ipairs(e[2]) do f[#f + 1] = ("%q"):format(x) end
    P(("    %s = { fields = { %s } },"):format(e[1], table.concat(f, ", ")))
end
P("}")
-- Everything but: unused arguments (212: handlers take what the client passes), values overwritten or unused
-- (31x), shadowing (4xx: `self` in nested methods).
P('ignore = { "212", "31.", "4.." }')
io.write(table.concat(out, "\n"), "\n")
